function isKopje(line: string) {
  return (
    line === "Voorwaarden" ||
    line === "Algemene Voorwaarden Autorijschool Vlam" ||
    /^Artikel\s+\d+/.test(line) ||
    /^ARTIKEL\s+\d+/.test(line) ||
    [
      "Voorwaarden voor de wijze van betaling",
      "Rijexamen en herexamen",
      "Annulering door de rijschool",
      "Lespakketten",
      "Vrijwaring",
      "Klachtenprocedure",
      "Indienen van klachten:",
      "Oplossing:",
      "Privacy en gegevensbescherming",
      "Verzameling en gebruik van gegevens:",
      "Bewaartermijn:",
      "Wijzigingen van de voorwaarden",
      "Gegevens van ons incassobureau",
      "Toepasselijk recht",
      "Geschillen",
    ].includes(line)
  );
}

export default function AlgemeneVoorwaardenPage() {
  const lines = TERMS_TEXT.split("\n");

  return (
    <>
      <Section className="pt-12 pb-20 md:pt-16">
        <SectionHeading
          title="Algemene voorwaarden"
          description="Hier vind je informatie over onze voorwaarden. Heb je een specifieke vraag? Neem gerust contact op."
        />
        <div className="mx-auto mt-10 max-w-4xl">
          <div className="space-y-3">
            {lines.map((line, idx) => {
              if (!line.trim()) {
                return <div key={`spacer-${idx}`} className="h-2" />;
              }

              if (isKopje(line)) {
                const isMain = line === "Voorwaarden";
                const isSub = line === "Algemene Voorwaarden Autorijschool Vlam";
                const className = isMain
                  ? "text-foreground text-2xl font-semibold tracking-tight"
                  : isSub
                    ? "text-foreground text-xl font-semibold tracking-tight"
                    : "text-foreground mt-4 text-lg font-semibold tracking-tight";

                const Tag = isMain ? "h2" : "h3";
                return (
                  <Tag key={`h-${idx}`} className={className}>
                    {line}
                  </Tag>
                );
              }

              return (
                <p
                  key={`p-${idx}`}
                  className="text-muted-foreground text-sm leading-relaxed"
                >
                  {line}
                </p>
              );
            })}
          </div>
        </div>
      </Section>

      <GraduatePhotosSection size="compact" />
    </>
  );
}
